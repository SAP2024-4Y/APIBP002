function pad(n) {
  return String(n).padStart(3, '0');
}

function isoAtUtc(baseDate, dayOffset, hour) {
  const d = new Date(baseDate);
  d.setUTCDate(d.getUTCDate() + dayOffset);
  d.setUTCHours(hour, 0, 0, 0);
  return d.toISOString();
}

function seed(db) {
  const existing = db.prepare('SELECT COUNT(*) AS c FROM products').get().c;
  if (existing > 0) return { seeded: false, products: existing };

  const insertProduct = db.prepare(`
    INSERT OR IGNORE INTO products
      (id, name, description, category, price_paise, currency, status, seller, rating, inventory, longitude, latitude, created_at)
    VALUES (@id, @name, @description, @category, @price_paise, @currency, @status, @seller, @rating, @inventory, @longitude, @latitude, @created_at)
  `);
  const insertSlot = db.prepare(`
    INSERT OR IGNORE INTO slots (id, product_id, starts_at, ends_at, capacity, booked)
    VALUES (@id, @product_id, @starts_at, @ends_at, @capacity, @booked)
  `);

  const now = new Date();
  const createdBase = new Date('2026-01-01T00:00:00Z').getTime();

  const tx = db.transaction(() => {
    CATALOGUE.forEach((row, i) => {
      const [name, category, price, status, rating, inventory, sellerPrefix] = row;
      const loc = CITIES[i % CITIES.length];
      // Spread coordinates slightly so nearby-search is interesting
      const jitterLon = loc.lon + (((i * 7) % 20) - 10) * 0.01;
      const jitterLat = loc.lat + (((i * 13) % 20) - 10) * 0.01;
      const id = `prod_${pad(i + 1)}`;
      insertProduct.run({
        id,
        name,
        description: `${name} — fulfilled from the ${loc.city} hub by ${sellerPrefix}. Part of the ShopMesh ${category} catalogue.`,
        category,
        price_paise: price,
        currency: 'INR',
        status,
        seller: `${sellerPrefix} · ${loc.city}`,
        rating,
        inventory,
        longitude: jitterLon,
        latitude: jitterLat,
        created_at: new Date(createdBase + i * 3600_000).toISOString(),
      });

      // 4 delivery slots per product: past, present-ish, and two future
      const slotTimes = [
        { dayOffset: -3, hour: 9  },
        { dayOffset:  0, hour: 14 },
        { dayOffset:  2, hour: 9  },
        { dayOffset:  4, hour: 15 },
      ];
      slotTimes.forEach(({ dayOffset, hour }, k) => {
        insertSlot.run({
          id: `slot_${pad(i + 1)}_${k + 1}`,
          product_id: id,
          starts_at: isoAtUtc(now, dayOffset, hour),
          ends_at: isoAtUtc(now, dayOffset, hour + 3),
          capacity: 5 + (i % 10),
          booked: k === 0 ? 1 : 0, // first slot has 1 booking for realism
        });
      });
    });

    // Deterministically-full slot on prod_001 — reproducible 409 SLOT_FULL demo
    insertSlot.run({
      id: 'slot_full_demo',
      product_id: 'prod_001',
      starts_at: isoAtUtc(now, 1, 18),
      ends_at: isoAtUtc(now, 1, 21),
      capacity: 1,
      booked: 1,
    });
  });

  tx();
  const count = db.prepare('SELECT COUNT(*) AS c FROM products').get().c;
  return { seeded: true, products: count };
}

function newId(prefix) {
  return `${prefix}_${crypto.randomUUID().replace(/-/g, '').slice(0, 20)}`;
}

